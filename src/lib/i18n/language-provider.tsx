interface LanguageContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: string, values?: Record<string, string | number>) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const language = useSyncExternalStore(subscribeToLanguage, getLanguageSnapshot, getServerLanguageSnapshot);

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const setLanguage = useCallback((next: Language) => {
    volatileLanguage = next;
    try {
      window.localStorage.setItem(STORAGE_KEY, next);
      languageWriteBlocked=false;
    } catch {
      languageWriteBlocked=true;
      // The preference still applies for this session when storage is unavailable.
    }
    languageListeners.forEach((listener) => listener());
  }, []);

  const t = useCallback((key: string, values?: Record<string, string | number>) => {
    const message = (language === "bn" ? interfaceBangla[key] : undefined) ?? messages[language][key] ?? (language === "bn" ? workspaceBangla[key] : undefined) ?? key;
    return values ? message.replace(/\{(\w+)\}/g, (token, name: string) => values[name] == null ? token : String(values[name])) : message;
  }, [language]);
  const value = useMemo(() => ({ language, setLanguage, t }), [language, setLanguage, t]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used inside LanguageProvider");
  return context;
}
